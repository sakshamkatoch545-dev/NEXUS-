def full_image_analysis(image: Image.Image) -> dict:
    """
    Run 13 forensic, neural, provenance, and signal processing engines and produce a final weighted verdict
    calibrated for modern AI diffusion models and localized AI edits.
    """
    working_image = image.copy()
    working_image.thumbnail((1024, 1024), Image.Resampling.LANCZOS)
    
    neural   = engine_neural_ensemble(working_image)
    clip     = engine_clip_semantic(working_image)
    texture  = engine_texture_smoothness(working_image)
    color    = engine_color_forensics(working_image)
    freq     = engine_frequency(working_image)
    edge     = engine_edge_sharpness(working_image)
    portrait = engine_portrait_style(working_image)
    face     = engine_face_symmetry(working_image)
    ela      = engine_ela_compression(working_image)
    watermark = engine_watermark_detection(working_image)
    ft_vit   = engine_fine_tuned_vit(working_image)
    provenance = engine_ai_provenance(working_image)
    manipulation = engine_ai_manipulation_and_inpainting(working_image)

    engines_dict = {
        "neural_ensemble": {
            "name": "Neural Network Ensemble",
            "icon": "🧠",
            **neural,
        },
        "clip_semantic": {
            "name": "CLIP Semantic Analysis",
            "icon": "🔬",
            **clip,
        },
        "texture_smoothness": {
            "name": "Texture Smoothness Analysis",
            "icon": "🎨",
            **texture,
        },
        "color_forensics": {
            "name": "Color & Saturation Forensics",
            "icon": "🌈",
            **color,
        },
        "frequency": {
            "name": "Frequency Domain (FFT)",
            "icon": "📊",
            **freq,
        },
        "edge_sharpness": {
            "name": "Background & Edge Analysis",
            "icon": "🔍",
            **edge,
        },
        "portrait_style": {
            "name": "Portrait Style Analysis",
            "icon": "🪞",
            **portrait,
        },
        "face_symmetry": {
            "name": "Face Symmetry & Micro-Texture",
            "icon": "👤",
            **face,
        },
        "ela_compression": {
            "name": "Error Level Analysis (ELA)",
            "icon": "🖼️",
            **ela,
        },
        "fine_tuned_vit": {
            "name": "Fine-Tuned ViT Classifier",
            "icon": "⚡",
            **ft_vit,
        },
        "watermark_detection": {
            "name": "Watermark Detection",
            "icon": "🏷️",
            **watermark,
        },
        "ai_provenance": {
            "name": "AI & Generator Provenance Engine",
            "icon": "🧬",
            **provenance,
        },
        "ai_manipulation": {
            "name": "AI Inpainting & Retouch Forensics",
            "icon": "🪄",
            **manipulation,
        },
    }

    total_engine_count = len(engines_dict)
    weighted_engine_scores = []
    for engine_key, engine in engines_dict.items():
        if engine["max"] <= 0:
            continue
        ai_percentage = engine["score"] / engine["max"] * 100
        weight = 15.0 if engine_key == "fine_tuned_vit" and engine.get("active") else 1.0
        if engine_key == "ai_provenance":
            weight = 1.5
        if engine_key == "ai_manipulation":
            weight = 1.2
        weighted_engine_scores.append((ai_percentage, weight))

    engine_ai_percentages = [score for score, _weight in weighted_engine_scores]
    high_risk_engine_count = sum(percent > 60 for percent in engine_ai_percentages)
    human_engine_count = total_engine_count - high_risk_engine_count

    total_weight = sum(weight for _score, weight in weighted_engine_scores)
    ai_conf = sum(score * weight for score, weight in weighted_engine_scores) / (total_weight * 100)
    human_conf = 1.0 - ai_conf

    # Real but Edited by AI decision logic
    is_edited_flag = bool(manipulation.get("is_edited", False))

    if ai_conf >= 0.58:
        verdict       = "AI-GENERATED"
        verdict_label = "🚨 AI-GENERATED"
    elif is_edited_flag and ai_conf <= 0.55:
        verdict       = "AI-EDITED"
        verdict_label = "🪄 LIKELY REAL BUT EDITED BY AI"
    elif human_conf >= 0.50:
        verdict       = "AUTHENTIC"
        verdict_label = "✅ AUTHENTIC"
    else:
        verdict       = "UNCERTAIN"
        verdict_label = "⚠️ UNCERTAIN"

    return {
        "verdict":          verdict,
        "verdict_label":    verdict_label,
        "confidence_score": round(ai_conf * 100, 1),
        "human_score":      round(human_conf * 100, 1),
        "is_ai_edited":     is_edited_flag or verdict == "AI-EDITED",
        "ai_edited_score":  round(float(manipulation.get("score", 0)), 1),
        "total_engine_count": total_engine_count,
        "high_risk_engine_count": high_risk_engine_count,
        "human_engine_count":     human_engine_count,
        "engines":          engines_dict,
        "ai_probability": round(ai_conf, 4),
        "real_probability": round(human_conf, 4),
        "confidence": round(abs(ai_conf - human_conf), 4),
        "nearest_generator": provenance.get("generator", "Unknown AI"),
        "similarity": round(provenance.get("raw", 0.5), 4),
        "detected_artifacts": [
            e.get("name", key) for key, e in engines_dict.items()
            if e.get("score", 0) >= 60
        ],
        "feature_scores": {key: round(float(e.get("score", 0)), 2) for key, e in engines_dict.items()},
        "reason": provenance.get("explanation", "Multi-engine forensic consensus."),
        "top_matches": [],
    }


def full_profile_analysis(
    image=None,
    username="",
    bio="",
    followers=0,
    posts=0,
    following=0,
    account_age_days=0,
    image_source=None,
):
    """Analyze an image and expose the legacy profile-analysis response shape.

    The Streamlit profile view and older callers use profile-oriented key names,
    while the primary detector returns an engine-oriented result.  Keep both
    APIs working by adapting the detector output instead of duplicating the
    image analysis.
    """
    # Older profile UI code uses ``image_source``.  Accept it as an alias so
    # both profile app variants can call this shared detector.
    if image is None:
        image = image_source
    if image is None:
        raise ValueError("An image is required for profile analysis.")

    analysis = full_image_analysis(image)
    score = analysis["confidence_score"]
    engines = analysis["engines"]

    metadata_score = 0
    red_flags = []
    if followers < 10 and following > 100:
        metadata_score += 30
        red_flags.append("Low followers with high following")
    if posts == 0:
        metadata_score += 25
        red_flags.append("No posts")
    if account_age_days and account_age_days < 30:
        metadata_score += 20
        red_flags.append("Recently created account")
    if len(username) > 12 and any(char.isdigit() for char in username):
        metadata_score += 15
        red_flags.append("Suspicious username pattern")
    if not bio.strip():
        metadata_score += 10
        red_flags.append("Empty profile bio")
    metadata_score = min(metadata_score, 100)

    return {
        "overall_suspicion_score": score,
        # Use the ASCII identifier here so legacy console callers also work
        # on Windows terminals that default to a non-UTF-8 code page.
        "overall_verdict": analysis["verdict"],
        "image_analysis": {
            "ai_probability": score / 100,
            "is_ai_generated": analysis["verdict"] == "AI-GENERATED",
            "confidence_level": "high" if score >= 65 else "medium" if score >= 40 else "low",
            "individual_results": engines,
        },
        "metadata_analysis": {
            "metadata_suspicion_score": metadata_score,
            "red_flags": red_flags,
        },
        "clip_score": engines["clip_semantic"]["score"],
        "artifact_score": engines["texture_smoothness"]["score"],
        "symmetry_score": engines["face_symmetry"]["score"],
        "frequency_score": engines["frequency"]["score"],
        "watermark_score": engines["watermark_detection"]["score"],
    }
