@st.cache_resource(show_spinner=False)
def _get_clip_resources():
    if "clip" not in _GLOBAL_CACHE:
        clip_model, _, clip_preprocess = open_clip.create_model_and_transforms(
            "ViT-B-32", pretrained="openai"
        )
        clip_model.eval()
        clip_tokenizer = open_clip.get_tokenizer("ViT-B-32")
        
        # Precompute static text embeddings once at startup
        tokens_prov = clip_tokenizer(PROMPTS_PROVENANCE)
        tokens_sem = clip_tokenizer(PROMPTS_SEMANTIC)
        with torch.inference_mode():
            txt_feat_prov = clip_model.encode_text(tokens_prov)
            txt_feat_prov = txt_feat_prov / txt_feat_prov.norm(dim=-1, keepdim=True)
            txt_feat_sem = clip_model.encode_text(tokens_sem)
            txt_feat_sem = txt_feat_sem / txt_feat_sem.norm(dim=-1, keepdim=True)
            
        _GLOBAL_CACHE["clip"] = (clip_model, clip_preprocess, clip_tokenizer, txt_feat_prov, txt_feat_sem)
    return _GLOBAL_CACHE["clip"]


def _encode_clip_image(image: Image.Image):
    """Encodes image into normalized CLIP feature vector once for all CLIP engines."""
    clip_model, clip_preprocess, _, _, _ = _get_clip_resources()
    tensor = clip_preprocess(image).unsqueeze(0)
    with torch.inference_mode():
        im_feat = clip_model.encode_image(tensor)
        im_feat = im_feat / im_feat.norm(dim=-1, keepdim=True)
    return im_feat


def _metadata_provenance(image: Image.Image) -> dict:
    """Return weak provenance hints; metadata is evidence, never a verdict."""
    info = {str(k).lower(): str(v).lower() for k, v in image.getexif().items()}
    text = " ".join(info.values())
    generators = {
        "chatgpt / openai": ("openai", "chatgpt", "dall-e", "gpt-image"),
        "gemini / google": ("google", "gemini", "imagen"),
        "midjourney": ("midjourney",),
        "adobe firefly": ("firefly", "adobe"),
    }
    hits = {name: sum(token in text for token in tokens) for name, tokens in generators.items()}
    best = max(hits, key=hits.get) if hits and max(hits.values()) else "Unknown AI"
    return {"metadata_hits": hits, "metadata_generator": best if max(hits.values()) else None,
            "has_exif": bool(info), "has_c2pa_hint": any(x in text for x in ("c2pa", "content credentials"))}


def engine_ai_provenance(image: Image.Image, precomputed_clip_feat=None) -> dict:
    """Dedicated ChatGPT/Gemini-style image provenance engine.
    Uses precomputed normalized CLIP representations for near-zero runtime latency.
    """
    meta = _metadata_provenance(image)
    semantic = 0.0
    provider = "Authentic Camera / No AI Match"
    try:
        if precomputed_clip_feat is not None:
            im = precomputed_clip_feat
        else:
            im = _encode_clip_image(image)
        _, _, _, txt_feat_prov, _ = _get_clip_resources()
        with torch.inference_mode():
            probs = (im @ txt_feat_prov.T).softmax(dim=-1)[0].cpu().numpy()
        real_prob = float(probs[0])
        ai_sum = float(probs[1] + probs[2] + probs[3])
        if real_prob > ai_sum or real_prob > 0.35:
            semantic = max(0.0, float(ai_sum * 0.2))
            provider = "Camera / Optical Capture"
        else:
            semantic = float(ai_sum)
            provider = ["ChatGPT / OpenAI", "Gemini / Google", "Unknown AI"][int(np.argmax(probs[1:]))]
    except Exception:
        pass
    evidence = []
    score = semantic * 60.0
    if meta["has_c2pa_hint"]:
        evidence.append("Content Credentials/C2PA metadata is present")
        score += 30
    if meta["metadata_generator"]:
        provider = meta["metadata_generator"]
        evidence.append(f"Metadata mentions {provider}")
        score += 30
    
    score = float(np.clip(score, 0, 100))
    if score < 20:
        evidence.append("Semantic feature profile matches authentic camera optical capture")
    else:
        evidence.append(f"Semantic generator-family compatibility aligned with {provider}")
    return {"score": round(score, 1), "max": 100, "raw": score / 100,
            "active": True, "generator": provider, "evidence": evidence,
            "explanation": "<br>".join("• " + item for item in evidence)}


