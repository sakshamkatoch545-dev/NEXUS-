def engine_ai_manipulation_and_inpainting(image: Image.Image) -> dict:
    """
    Scans for localized AI generative inpainting, object removal, Snapchat / AR filters,
    and retouching on otherwise authentic camera photographs using robust wavelet residual disparity.
    """
    try:
        try:
            import pywt
            has_pywt = True
        except ImportError:
            has_pywt = False
        from scipy.ndimage import laplace
        import scipy.stats as stats
        
        rgb = np.asarray(image.convert("RGB")).astype(np.float32) / 255.0
        h, w, _ = rgb.shape
        r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
        gray = 0.299 * r + 0.587 * g + 0.114 * b

        grid_r, grid_c = 6, 6
        th, tw = max(4, h // grid_r), max(4, w // grid_c)
        
        tile_noise = []
        tile_ratio = []
        tile_lap = []
        
        for r_idx in range(grid_r):
            for c_idx in range(grid_c):
                t = gray[r_idx*th:(r_idx+1)*th, c_idx*tw:(c_idx+1)*tw]
                if has_pywt:
                    coeffs = pywt.dwt2(t, 'db4')
                    _, (_, _, hh) = coeffs
                    sigma = float(np.median(np.abs(hh)) / 0.6745)
                else:
                    k = np.array([[1, -2, 1], [-2, 4, -2], [1, -2, 1]], dtype=np.float32)
                    res = cv2.filter2D(t, -1, k)
                    sigma = float(np.sum(np.abs(res)) * np.sqrt(0.5 * np.pi) / (6.0 * max(1, (th - 2) * (tw - 2))))
                
                l_var = float(laplace(t).var())
                
                tile_noise.append(sigma)
                tile_lap.append(l_var)
                tile_ratio.append(sigma / (np.sqrt(l_var) + 1e-4))
                
        n_arr = np.array(tile_noise, dtype=np.float32)
        r_arr = np.array(tile_ratio, dtype=np.float32)
        l_arr = np.array(tile_lap, dtype=np.float32)
        
        n_med = float(np.median(n_arr))
        n_iqr = float(stats.iqr(n_arr)) + 1e-5
        n_z = np.abs(n_arr - n_med) / n_iqr
        
        r_med = float(np.median(r_arr))
        r_iqr = float(stats.iqr(r_arr)) + 1e-5
        r_z = np.abs(r_arr - r_med) / n_iqr
        
        anomalies = int(np.sum((n_z > 3.8) & (r_z > 3.5)))
        max_nz = float(np.max(n_z))
        max_rz = float(np.max(r_z))
        
        noise_cv = float(n_arr.std() / (n_arr.mean() + 1e-6))
        lap_cv = float(l_arr.std() / (l_arr.mean() + 1e-6))
        is_ar_filter = bool(anomalies >= 2 and noise_cv > 0.65 and lap_cv > 0.85 and max_rz > 3.8)
        is_edited = bool(anomalies >= 2 and max_nz >= 4.0 and max_rz >= 3.5) or is_ar_filter
        
        findings = []
        if is_ar_filter:
            score = float(np.clip(max(max_nz * 15.0, lap_cv * 60.0), 65.0, 95.0))
            findings.append(f"Detected AR filter / digital overlay / beauty smoothing (noise disparity z={max_nz:.2f}).")
        elif is_edited:
            score = float(np.clip(max_nz * 12.0, 65.0, 100.0))
            findings.append(f"Detected localized AI inpainting / object removal ({anomalies} anomaly patch(es), noise disparity z={max_nz:.2f}).")
        else:
            score = float(np.clip(min(max_rz, 2.5) * 4.0, 0.0, 15.0))
            findings.append("Uniform sensor noise distribution across all image tiles.")

        # Calculate suspicious region bounding boxes in normalized coordinates [0.0, 1.0]
        regions = []
        for r_idx in range(grid_r):
            for c_idx in range(grid_c):
                idx = r_idx * grid_c + c_idx
                if n_z[idx] > 3.0 or r_z[idx] > 3.0:
                    patch_score = round(float(min(100.0, max(n_z[idx] * 18.0, r_z[idx] * 18.0))), 1)
                    regions.append({
                        "x": round(float(c_idx / grid_c), 3),
                        "y": round(float(r_idx / grid_r), 3),
                        "width": round(float(1.0 / grid_c), 3),
                        "height": round(float(1.0 / grid_r), 3),
                        "score": patch_score
                    })

        heatmap = {
            "available": True,
            "width": 512,
            "height": 512,
            "regions": regions
        }

        manip_type = None
        if is_ar_filter:
            manip_type = "ai_face_filter"
        elif is_edited and anomalies >= 2:
            manip_type = "ai_inpainting"
        elif is_edited:
            manip_type = "synthetic_retouching"

        manipulation_block = {
            "detected": bool(is_edited),
            "type": manip_type,
            "severity": round(float(score), 1)
        }

        return {
            "score": round(score, 1),
            "max": 100,
            "raw": score / 100.0,
            "is_edited": is_edited,
            "is_ar_filter": is_ar_filter,
            "anomalies": anomalies,
            "regions": regions,
            "heatmap": heatmap,
            "manipulation": manipulation_block,
            "explanation": "<br>".join(f"• {f}" for f in findings)
        }
    except Exception as exc:
        return {
            "score": 0, "max": 100, "raw": 0.0, "is_edited": False, "anomalies": 0,
            "regions": [], "heatmap": {"available": False, "width": 512, "height": 512, "regions": []},
            "manipulation": {"detected": False, "type": None, "severity": 0.0},
            "explanation": f"Inpainting scan skipped: {exc}"
        }


