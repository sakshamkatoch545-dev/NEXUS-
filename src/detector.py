@st.cache_resource(show_spinner=False)
def _get_clip_resources():
    clip_model, _, clip_preprocess = open_clip.create_model_and_transforms(
        "ViT-B-32", pretrained="openai"
    )
    clip_tokenizer = open_clip.get_tokenizer("ViT-B-32")
    return clip_model, clip_preprocess, clip_tokenizer


def _metadata_provenance(image: Image.Image) -> dict:
    """Return weak provenance hints; metadata is evidence, never a verdict."""
    info = {str(k).lower(): str(v).lower() for k, v in image.getexif().items()}
    text = " ".join(info.values())
    generators = {
        "chatgpt / openai": ("openai", "chatgpt", "dall-e", "gpt-image"),
        "gemini / google": ("google", "gemini", "imagen"),
        "midjourney": ("midjourney",),
        "adobe firefly": ("firefly", "adobe"),
    }
    hits = {name: sum(token in text for token in tokens) for name, tokens in generators.items()}
    best = max(hits, key=hits.get) if hits and max(hits.values()) else "Unknown AI"
    return {"metadata_hits": hits, "metadata_generator": best if max(hits.values()) else None,
            "has_exif": bool(info), "has_c2pa_hint": any(x in text for x in ("c2pa", "content credentials"))}


def engine_ai_provenance(image: Image.Image) -> dict:
    """Dedicated ChatGPT/Gemini-style image provenance engine.

    It deliberately reports *compatibility* with generator families rather than
    claiming to identify an exact provider. Provider fingerprints are not stable
    after resize, screenshots, or social-media recompression.
    """
    meta = _metadata_provenance(image)
    prompts = [
        "an authentic camera photograph with optical lens and sensor noise",
        "a photorealistic image generated by ChatGPT or OpenAI GPT Image",
        "a photorealistic image generated by Google Gemini or Imagen",
        "a synthetic diffusion-model portrait with rendered texture",
    ]
    semantic = 0.5
    provider = "Unknown AI"
    try:
        clip_model, clip_preprocess, clip_tokenizer = _get_clip_resources()
        tensor = clip_preprocess(image).unsqueeze(0)
        tokens = clip_tokenizer(prompts)
        with torch.inference_mode():
            im = clip_model.encode_image(tensor)
            tx = clip_model.encode_text(tokens)
            probs = (im @ tx.T).softmax(dim=-1)[0].cpu().numpy()
        semantic = float((probs[1] + probs[2] + probs[3]) / max(probs.sum(), 1e-8))
        provider = ["ChatGPT / OpenAI", "Gemini / Google", "Unknown AI"][int(np.argmax(probs[1:]))]
    except Exception:
        pass
    evidence = []
    score = semantic * 75.0
    if meta["has_c2pa_hint"]:
        evidence.append("Content Credentials/C2PA metadata is present")
        score += 20
    if meta["metadata_generator"]:
        provider = meta["metadata_generator"]
        evidence.append(f"Metadata mentions {provider}")
        score += 20
    if not meta["has_exif"]:
        evidence.append("No camera EXIF metadata (weak signal; social apps often remove it)")
        score += 5
    score = float(np.clip(score, 0, 100))
    evidence.append("Semantic generator-family compatibility is probabilistic, not provider attribution")
    return {"score": round(score, 1), "max": 100, "raw": score / 100,
            "active": True, "generator": provider, "evidence": evidence,
            "explanation": "<br>".join("• " + item for item in evidence)}


