# ENGINE 4 — COLOR SATURATION FORENSICS
# ═════════════════════════════════════════════════════

def engine_color_forensics(image: Image.Image) -> dict:
    """Detect oversaturated AI diffusion skin tones and neon artifacts."""
    img = np.array(image)
    hsv = cv2.cvtColor(img, cv2.COLOR_RGB2HSV)
    sat = hsv[:, :, 1].astype(np.float64)
    val = hsv[:, :, 2].astype(np.float64)

    # Isolate skin tone hues (Hue 0-25 or 160-180 in OpenCV HSV) to measure skin tone saturation specifically
    skin_mask = ((hsv[:, :, 0] < 25) | (hsv[:, :, 0] > 165)) & (val > 40) & (sat > 20)
    if np.sum(skin_mask) > 100:
        sat_fg = sat[skin_mask]
    else:
        dark_mask = (val < 230) & (val > 30)
        sat_fg = sat[dark_mask]
        
    mean_sat_fg = float(np.mean(sat_fg)) if sat_fg.size > 0 else 0
    std_sat_fg  = float(np.std(sat_fg))  if sat_fg.size > 0 else 0

    score = 0
    findings = []

    # Skin saturation: AI diffusion skin ~145-180, real skin ~40-95
    if mean_sat_fg > 145:
        score += 65
        findings.append(
            f"<b>Hyper-saturated skin tone profile (mean={mean_sat_fg:.0f})</b> — "
            f"Synthetic diffusion models frequently produce hyper-vivid, oversaturated skin tones."
        )
    elif mean_sat_fg > 115:
        score += 35
        findings.append(
            f"<b>Elevated skin tone saturation (mean={mean_sat_fg:.0f})</b> — "
            f"Above average saturation."
        )
    elif mean_sat_fg > 85:
        score += 10
        findings.append(f"Moderate skin saturation (mean={mean_sat_fg:.0f}) — consistent with warm indoor lighting or flash.")
    else:
        findings.append(
            f"Natural skin tone saturation (mean={mean_sat_fg:.0f}) — "
            f"Consistent with authentic camera sensor response in natural/indoor lighting."
        )

    # Low saturation variance (flat color): AI ~25, real ~45
    if std_sat_fg < 22:
        score += 25
        findings.append(
            f"<b>Unnaturally uniform saturation (std={std_sat_fg:.1f})</b> — "
            f"AI generator color-quantisation signature."
        )
    elif std_sat_fg < 30:
        score += 15
        findings.append(f"Slightly low saturation variance (std={std_sat_fg:.1f}).")
    else:
        findings.append(f"Natural saturation diversity (std={std_sat_fg:.1f}).")

    # Near-white background proportion (studio cutout trick used by SDXL)
    white_mask = (val > 240) & (sat < 25)
    white_pct  = float(white_mask.mean() * 100)
    if white_pct > 35:
        score += 15
        findings.append(
            f"<b>Large near-white background ({white_pct:.0f}%)</b> — "
            f"Common in synthetic studio renders."
        )
    else:
        findings.append(
            f"No large white background area ({white_pct:.0f}% near-white pixels) — "
            f"Consistent with real photography."
        )

    score = min(score, 100)

    return {
        "score": score,
        "max":   100,
        "raw":   score / 100,
        "explanation": "<br>".join(f"• {f}" for f in findings),
    }


