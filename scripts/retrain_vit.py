"""
retrain_vit.py  --  NEXUS+ ViT Retrainer v2  (Real AI Images + LFW Real Photos)
=================================================================================
Dataset sources:
  REAL  ->  LFW face dataset via sklearn  (5,985 genuine photographic portraits)
  AI    ->  13 images genuinely generated by an AI image model  (core signal)
            + supplementary synthetic PIL samples for volume

Strategy:
  - WeightedRandomSampler gives the 13 real-AI images 5x oversampling weight
    so the model learns the true AI texture fingerprint, not just PIL patterns.
  - 3 fine-tuning epochs on the existing fine_tuned_vit/ checkpoint.
  - Saves updated model + eval_results.json + training_curves.png.

Run:
    .\\venv\\Scripts\\python.exe scripts\\retrain_vit.py
"""

