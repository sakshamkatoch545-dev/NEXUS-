    print(f"{C_CYAN}│{C_RESET}  {C_BOLD}SHA-256:{C_RESET}          {C_YELLOW}{specs.get('sha256')}{C_RESET}")
    print(f"{C_CYAN}│{C_RESET}  {C_BOLD}Perceptual dHash:{C_RESET} {C_MAGENTA}{specs.get('dhash')}{C_RESET}")
    print(f"{C_CYAN}│{C_RESET}  {C_BOLD}Resolution:{C_RESET}       {res.get('width')}x{res.get('height')} px ({res.get('aspect_ratio')}:1) · {res.get('megapixels', 0)} MP")
