def _get_cached_registry():
    reg_file = ROOT / "results" / "authenticated_registry.json"
    if reg_file.exists():
        try:
            with open(reg_file, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}
    return {}

