def train_single_interactive():
    print(f"\n{C_BOLD}{C_MAGENTA}=== [1] TRAIN & REMEMBER IMAGE ==={C_RESET}")
    path_raw = input(f"{C_CYAN}Enter image file path (or drag & drop): {C_RESET}")
    img_path = clean_input_path(path_raw)

    if not os.path.exists(img_path):
        print(f"{C_RED}[ERROR] File not found: {img_path}{C_RESET}")
        return

    try:
        Image.open(img_path).verify()
    except Exception as e:
        print(f"{C_RED}[ERROR] Invalid image file: {e}{C_RESET}")
        return

    print(f"\n{C_BOLD}Select Training Category / Ground Truth Label:{C_RESET}")
    print(f"  {C_RED}[1] GENERATED BY AI{C_RESET}     (Fully synthetic Midjourney, Flux, SDXL, DALL-E render)")
    print(f"  {C_YELLOW}[2] AI-EDITED{C_RESET}            (Authentic camera base with AI inpainting/generative fill)")
    print(f"  {C_GREEN}[3] AUTHENTIC / REAL{C_RESET}     (Original genuine optical camera capture)")
    
    choice = input(f"{C_CYAN}Select option [1-3] (Default 1): {C_RESET}").strip()
    if choice == "2":
        label = "ai_edited"
        label_str = "AI-EDITED"
    elif choice == "3":
        label = "real"
        label_str = "AUTHENTIC / REAL"
    else:
        label = "generated_by_ai"
        label_str = "GENERATED BY AI"

    notes = input(f"{C_CYAN}Enter custom notes / exemplar description (optional): {C_RESET}").strip()

    print(f"\n{C_YELLOW}Extracting 14-engine forensic specs and computing perceptual fingerprints...{C_RESET}")
    start_t = time.time()
    from src.detector import learn_and_register_image
    record = learn_and_register_image(img_path, label=label, notes=notes, force_override=True)
    dur = time.time() - start_t

    print(f"\n{C_GREEN}{C_BOLD}[TRAINING COMPLETE] — IMAGE LOCKED IN PERMANENT MEMORY BANK ({dur:.2f}s){C_RESET}")
