def list_memory_bank():
    reg = _get_cached_registry()
    print(f"\n{C_BOLD}{C_MAGENTA}=== [3] TRAINED FORENSIC MEMORY BANK ({len(reg)} REGISTERED EXEMPLARS) ==={C_RESET}\n")
    if not reg:
        print(f"{C_YELLOW}Memory bank is empty. Use Option 1 to train your first image.{C_RESET}\n")
        return

    print(f"{'#':<3} | {'FILENAME':<24} | {'LABEL':<16} | {'VERDICT':<24} | {'REGISTERED AT':<20}")
    print("-" * 96)
    for idx, (sha, item) in enumerate(reg.items(), 1):
        fn = item.get("filename", "unknown")[:22]
        lbl = item.get("label", "unknown")[:14]
        vrd = item.get("verdict_label", item.get("verdict", "UNKNOWN"))[:22]
        reg_t = item.get("registered_at", "N/A")[:19]
        print(f"{idx:<3} | {fn:<24} | {lbl:<16} | {vrd:<24} | {reg_t:<20}")
    print("-" * 96 + "\n")


def batch_train_interactive():
    print(f"\n{C_BOLD}{C_YELLOW}=== [4] BATCH TRAIN DIRECTORY ==={C_RESET}")
    path_raw = input(f"{C_CYAN}Enter directory path containing images: {C_RESET}")
    folder_path = clean_input_path(path_raw)

    if not os.path.isdir(folder_path):
        print(f"{C_RED}[ERROR] Directory not found: {folder_path}{C_RESET}")
        return

    valid_exts = {".png", ".jpg", ".jpeg", ".webp"}
    files = [os.path.join(folder_path, f) for f in os.listdir(folder_path) if Path(f).suffix.lower() in valid_exts]

    if not files:
        print(f"{C_RED}[ERROR] No images found in {folder_path}{C_RESET}")
        return

    print(f"\nFound {len(files)} image(s). Select category for all images in folder:")
    print(f"  {C_RED}[1] GENERATED BY AI{C_RESET}")
    print(f"  {C_YELLOW}[2] AI-EDITED{C_RESET}")
    print(f"  {C_GREEN}[3] AUTHENTIC / REAL{C_RESET}")

    choice = input(f"{C_CYAN}Select option [1-3] (Default 1): {C_RESET}").strip()
    if choice == "2":
        label = "ai_edited"
    elif choice == "3":
        label = "real"
    else:
        label = "generated_by_ai"

    notes = input(f"{C_CYAN}Enter batch tag / notes (optional): {C_RESET}").strip()

    print(f"\n{C_YELLOW}Processing batch training...{C_RESET}")
    from src.detector import learn_and_register_image
    success_count = 0
    for idx, fpath in enumerate(files, 1):
        try:
            print(f"  [{idx}/{len(files)}] Learning {os.path.basename(fpath)}... ", end="", flush=True)
            learn_and_register_image(fpath, label=label, notes=notes, force_override=True)
            print(f"{C_GREEN}DONE{C_RESET}")
            success_count += 1
        except Exception as e:
            print(f"{C_RED}FAILED ({e}){C_RESET}")

    print(f"\n{C_GREEN}{C_BOLD}[BATCH COMPLETE]: Successfully trained {success_count}/{len(files)} image(s).{C_RESET}\n")


def interactive_loop():
    while True:
        print_banner()
        print(f"{C_BOLD}AVAILABLE ACTIONS:{C_RESET}")
        print(f"  {C_MAGENTA}[1]{C_RESET} Train & Remember Single Image (Extract specs + Lock verdict)")
        print(f"  {C_CYAN}[2]{C_RESET} Analyze & Spec-Match Suspect Image Against Memory Bank")
        print(f"  {C_YELLOW}[3]{C_RESET} Batch Train Entire Directory")
        print(f"  {C_GREEN}[4]{C_RESET} View Trained Knowledge Bank")
        print(f"  {C_RED}[5]{C_RESET} Exit")

        choice = input(f"\n{C_BOLD}Enter choice [1-5]: {C_RESET}").strip()
        if choice == "1":
            train_single_interactive()
        elif choice == "2":
            match_single_interactive()
        elif choice == "3":
            batch_train_interactive()
        elif choice == "4":
            list_memory_bank()
        elif choice in ("5", "q", "exit"):
            print(f"\n{C_CYAN}Exiting NEXUS+ Forensic Trainer. Goodbye!{C_RESET}\n")
            break
        else:
            print(f"{C_RED}Invalid option, please choose 1-5.{C_RESET}")
        
        input(f"\n{C_DIM}Press Enter to return to menu...{C_RESET}")


def main():
    parser = argparse.ArgumentParser(description="NEXUS+ Forensic Training & Memory Spec-Matching Tool")
    parser.add_argument("--train", type=str, help="Path to image to train and lock in memory")
    parser.add_argument("--label", type=str, default="generated_by_ai", choices=["generated_by_ai", "ai", "ai_edited", "edited", "real", "authentic"], help="Ground truth label")
    parser.add_argument("--notes", type=str, default="", help="Optional notes/tags for the trained image")
    parser.add_argument("--match", type=str, help="Path to suspect image to analyze and spec-match against memory")
    parser.add_argument("--batch", type=str, help="Path to directory for batch training")
    parser.add_argument("--list", action="store_true", help="List all trained images in memory bank")

    args = parser.parse_args()

    if args.list:
        list_memory_bank()
        return

    if args.train:
        img_path = clean_input_path(args.train)
        if not os.path.exists(img_path):
            print(f"{C_RED}[ERROR] File not found: {img_path}{C_RESET}")
            sys.exit(1)
        from src.detector import learn_and_register_image
        record = learn_and_register_image(img_path, label=args.label, notes=args.notes)
        print(f"{C_GREEN}[SUCCESS] Trained and remembered {os.path.basename(img_path)}{C_RESET}")
        print(f"Verdict: {record['verdict_label']} | SHA: {record['sha256'][:12]} | Dataset: {record['dataset_path']}")
        display_specs_card(record["forensic_specs"], title="LEARNED SPECS")
        return

    if args.match:
        img_path = clean_input_path(args.match)
        if not os.path.exists(img_path):
            print(f"{C_RED}[ERROR] File not found: {img_path}{C_RESET}")
            sys.exit(1)
        img = Image.open(img_path).convert("RGB")
        from src.detector import match_image_against_registry
        match_data = match_image_against_registry(img)
        if match_data.get("matched"):
            ex = match_data["exemplar"]
            print(f"{C_GREEN}[MATCH CONFIRMED] Similarity: {match_data['similarity']:.1f}% ({match_data['match_type']}){C_RESET}")
            print(f"Exemplar: {ex.get('filename')} | Verdict: {match_data['trained_verdict_label']}")
        else:
            print(f"{C_YELLOW}[NO MATCH] Similarity: {match_data.get('similarity', 0.0):.1f}%{C_RESET}")
        return

    if args.batch:
        folder = clean_input_path(args.batch)
        if not os.path.isdir(folder):
            print(f"{C_RED}[ERROR] Directory not found: {folder}{C_RESET}")
            sys.exit(1)
        valid_exts = {".png", ".jpg", ".jpeg", ".webp"}
        files = [os.path.join(folder, f) for f in os.listdir(folder) if Path(f).suffix.lower() in valid_exts]
        from src.detector import learn_and_register_image
        for f in files:
            learn_and_register_image(f, label=args.label, notes=args.notes)
        print(f"{C_GREEN}[SUCCESS] Batch trained {len(files)} images.{C_RESET}")
        return

    # Default to interactive menu
    interactive_loop()


if __name__ == "__main__":
    main()
